// Fonction pour changer la langue
function changeLanguage(lang) {
  try {
    document.documentElement.lang = lang;
    localStorage.setItem('preferredLanguage', lang);
    updateTexts(lang);
    updateLanguageButtons(lang);
    updateCVLinks(lang);
  } catch (error) {
    console.error('Error changing language:', error);
  }
}

// Rendre accessible depuis le HTML
window.changeLanguage = changeLanguage;

// Fonction de mise à jour des textes
function updateTexts(lang) {
  const elements = document.querySelectorAll('[data-translate]');

  elements.forEach(element => {
    try {
      const key = element.dataset.translate;
      const keys = key.split('.');

      let text = translations[lang];
      for (const k of keys) {
        text = text ? text[k] : undefined;
      }

      if (text) {
        if (element.tagName === 'TITLE') {
          element.textContent = text;
        } else if (element.hasAttribute('aria-label')) {
          element.setAttribute('aria-label', text);
        } else {
          element.innerHTML = text; // innerHTML pour supporter les <a>
        }
      }
    } catch (error) {
      console.error('Error updating text for element:', element, error);
    }
  });
}

// Fonction pour mettre à jour les liens CV selon la langue
function updateCVLinks(lang) {
  const cvFile = lang === 'en' ? 'uploads/laurence_pirard_26_en.pdf' : 'uploads/laurence_pirard_26.pdf';
  document.querySelectorAll('[data-cv]').forEach(link => {
    link.href = cvFile;
  });
}

// Fonction pour mettre à jour l'état des boutons de langue
function updateLanguageButtons(lang) {
  const langButtons = document.querySelectorAll('.lang-btn');

  langButtons.forEach(btn => {
    try {
      btn.classList.toggle('active', btn.dataset.lang === lang);
    } catch (error) {
      console.error('Error updating language button:', btn, error);
    }
  });
}

// Initialisation au chargement de la page
document.addEventListener('DOMContentLoaded', function() {
  try {
    const savedLang = localStorage.getItem('preferredLanguage') || 'fr';
    changeLanguage(savedLang);
  } catch (error) {
    console.error('Error during initialization:', error);
    changeLanguage('fr');
  }
});

